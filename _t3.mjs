import * as plugin from './index.js';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const reg = {};
const ctx = { skills:{register:()=>{}}, tools:{register:(t)=>{reg.tool=t;}}, commands:{register:()=>{}}, systemPrompt:{section:()=>{}}, logger:{warn:m=>console.log('WARN',m)},
  inject:function(l,f){for(const k of l) if(this[k]) f(this);} };
plugin.apply(ctx,{});
const dir = mkdtempSync(join(tmpdir(),'sp3-'));
const exec = { agent:{ session:{ header:{ cwd: dir } } } };
const call = async (a,p)=>{ const o = await reg.tool.execute({action:a, payload_json:p?JSON.stringify(p):undefined}, exec); return o; };
const c = await call('subject.create',{name:'通信原理',exam:'2026-12-01'});
console.log('create ok:', c.ok, c.name);
const s = {subject:'通信原理'};
const sp = await call('split.pdf',{...s, path:'G:\\workplace\\prepare\\题目\\第四章作业题.pdf'});
console.log('split:', sp.ok, sp.totalPages, sp.pageFiles);
const pl = await call('plan.coverage',{...s, sections:[{title:'第1章 绪论', book:'1.1', verdict:'可跳'}]});
console.log('plan:', pl.count, pl.next.title);
const d = await call('draft.new',{...s, title:'第1章 绪论'});
const pt = await call('draft.patch',{...s, id:d.id, action:'supplement', note:'两张截图'});
console.log('draft:', d.id, pt.status);
const ls = await call('subject.list',{});
console.log('list:', ls.count, ls.subjects[0].books, ls.subjects[0].tasks);
const rm = await call('subject.remove',{...s, mode:'all', confirm:'通信原理'});
console.log('purge:', rm.ok);
console.log('DIR='+dir);
